bool block_cell(int shape, int angle, int row, int column)
{
    return kBlocks[shape][angle][row][column] != 0;
}

int make_new_block(int stick_rate)
{
    if (std::rand() % 100 <= stick_rate) {
        return 0;
    }
    return std::rand() % (kShapeCount - 1) + 1;
}

Piece make_start_piece(int shape)
{
    return Piece{shape, 0, 5, -3};
}

